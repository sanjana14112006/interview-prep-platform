// Question Schema with references for both technical & behavioral questions
const questionItemSchema = {
    type: "OBJECT",
    properties: {
        question: { type: "STRING" },
        intention: { type: "STRING" },
        answer: { type: "STRING" },
        references: {
            type: "ARRAY",
            description: "1-2 official documentation links, RFCs, or engineering guides directly relevant to the topic",
            items: {
                type: "OBJECT",
                properties: {
                    title: { type: "STRING", description: "e.g. Official PyTorch Docs, NVIDIA TensorRT Guide, MDN Web Docs" },
                    url: { type: "STRING", description: "Direct valid HTTPS documentation URL" }
                },
                required: ["title", "url"]
            }
        }
    },
    required: ["question", "intention", "answer", "references"]
};

// Full Interview Prep Report JSON Schema
const interviewReportJsonSchema = {
    type: "OBJECT",
    properties: {
        title: { 
            type: "STRING", 
            description: "The targeted role title" 
        },
        matchScore: { 
            type: "NUMBER", 
            description: "An integer match score between 0 and 100" 
        },
        technicalQuestions: {
            type: "ARRAY",
            description: "6 to 8 rigorous, role-tailored technical interview questions covering fundamentals, architecture, and real-time edge cases",
            items: questionItemSchema
        },
        behavioralQuestions: {
            type: "ARRAY",
            description: "4 to 5 scenario-based behavioral questions evaluating leadership, conflict, and communication using the STAR framework",
            items: questionItemSchema
        },
        skillGaps: {
            type: "ARRAY",
            description: "List of skills missing or needing improvement",
            items: {
                type: "OBJECT",
                properties: {
                    skill: { type: "STRING" },
                    severity: { 
                        type: "STRING", 
                        enum: ["low", "medium", "high"] 
                    }
                },
                required: ["skill", "severity"]
            }
        },
        preparationPlan: {
            type: "ARRAY",
            description: "Structured 7-day preparation schedule starting from Day 1 to Day 7",
            items: {
                type: "OBJECT",
                properties: {
                    day: { type: "NUMBER" },
                    focus: { type: "STRING" },
                    tasks: {
                        type: "ARRAY",
                        items: { type: "STRING" }
                    }
                },
                required: ["day", "focus", "tasks"]
            }
        }
    },
    required: [
        "title",
        "matchScore",
        "technicalQuestions",
        "behavioralQuestions",
        "skillGaps",
        "preparationPlan"
    ]
};



// JSON Schema for 1-Page ATS Resume
const resumeJsonSchema = {
    type: "OBJECT",
    properties: {
        fullName: { type: "STRING" },
        contact: {
            type: "OBJECT",
            properties: {
                email: { type: "STRING" },
                phone: { type: "STRING" },
                linkedin: { type: "STRING" },
                github: { type: "STRING" }
            },
            required: ["email", "phone"]
        },
        summary: { type: "STRING" },
        skills: {
            type: "ARRAY",
            items: {
                type: "OBJECT",
                properties: {
                    category: { type: "STRING" },
                    items: { type: "ARRAY", items: { type: "STRING" } }
                },
                required: ["category", "items"]
            }
        },
        experience: {
            type: "ARRAY",
            items: {
                type: "OBJECT",
                properties: {
                    role: { type: "STRING" },
                    company: { type: "STRING" },
                    duration: { type: "STRING" },
                    highlights: { type: "ARRAY", items: { type: "STRING" } }
                },
                required: ["role", "company", "duration", "highlights"]
            }
        },
        projects: {
            type: "ARRAY",
            items: {
                type: "OBJECT",
                properties: {
                    title: { type: "STRING" },
                    techStack: { type: "STRING" },
                    highlights: { type: "ARRAY", items: { type: "STRING" } }
                },
                required: ["title", "techStack", "highlights"]
            }
        },
        education: {
            type: "ARRAY",
            items: {
                type: "OBJECT",
                properties: {
                    degree: { type: "STRING" },
                    institution: { type: "STRING" },
                    year: { type: "STRING" }
                },
                required: ["degree", "institution", "year"]
            }
        }
    },
    required: ["fullName", "contact", "summary", "skills", "projects", "education"]
};

async function generateInterviewReport({ resume, selfDescription, jobDescription }) {
    const prompt = `You are an expert technical interviewer. Analyze candidate data and job description.
Candidate Resume: ${resume || "N/A"}
Candidate Notes: ${selfDescription || "N/A"}
Target Job Description: ${jobDescription || "N/A"}`;

    const response = await ai.models.generateContent({
        model: "gemini-3.5-flash-lite",
        contents: prompt,
        config: {
            responseMimeType: "application/json",
            responseSchema: interviewReportJsonSchema
        }
    });

    return JSON.parse(response.text);
}

